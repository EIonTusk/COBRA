#!/usr/bin/env node
/**
 * Regenerate worker/src/community/openings.data.ts from the lichess
 * chess-openings table (CC0, https://github.com/lichess-org/chess-openings).
 *
 *   node scripts/gen-community-openings.mjs <dir with a.tsv … e.tsv>
 *
 * Each row's PGN is replayed with chessops and keyed by the same EPD fen key
 * the app uses (`fenKeyFromFen`), so the Worker can name every position of a
 * published tree without calling the explorer.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Chess } from 'chessops/chess';
import { makeFen } from 'chessops/fen';
import { parseSan } from 'chessops/san';

const dir = process.argv[2];
if (!dir) {
	console.error('usage: gen-community-openings.mjs <dir>');
	process.exit(1);
}

const byKey = new Map();
for (const f of ['a', 'b', 'c', 'd', 'e']) {
	const lines = readFileSync(join(dir, `${f}.tsv`), 'utf8')
		.split('\n')
		.slice(1);
	for (const line of lines) {
		if (!line.trim()) continue;
		const [eco, name, pgn] = line.split('\t');
		const pos = Chess.default();
		for (const tok of pgn.split(/\s+/)) {
			if (!tok || /^\d+\.$/.test(tok)) continue;
			const move = parseSan(pos, tok);
			if (!move) throw new Error(`bad move ${tok} in ${eco} ${name}`);
			pos.play(move);
		}
		const key = makeFen(pos.toSetup(), { epd: true });
		const prev = byKey.get(key);
		// Several names can share a position (transpositions); keep the most
		// specific one.
		if (!prev || name.length > prev[1].length) byKey.set(key, [eco, name]);
	}
}

const body = [...byKey.entries()]
	.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
	.map(([k, [eco, name]]) => `${k}\t${eco}\t${name}`)
	.join('\n');

const out = `// Generated by scripts/gen-community-openings.mjs from the lichess
// chess-openings table (CC0). Do not edit by hand.
// Format: one "<epd fen key>\\t<eco>\\t<name>" per line.
export const OPENINGS_TSV = ${JSON.stringify(body)};
`;
writeFileSync(new URL('../worker/src/community/openings.data.ts', import.meta.url), out);
console.log(`${byKey.size} positions`);
